#!/usr/bin/env python3
"""Compile a C patch into a blob for free flash (docs/patch-howto.md).

  patch_build.py patches/demo_note_hook/patch.py      build and print the budget

Used by tools/patch.py for definitions that have SOURCES. The steps:

  1. generate, in the build directory (work/build/<NAME>/):
     layout.ld      FREE_FLASH = [origin, FLASH_LIMIT), PATCH_RAM = CCM;
     fw_symbols.ld  every function (address | 1) and global of the symbols
                    CSV, so C can call firmware code and read its state;
  2. compile the patch's SOURCES and patches/common/*.c for Cortex-M4
     Thumb-2, hard float like the firmware, no libc;
  3. link with patches/common/patch.ld (+ libgcc), and refuse:
     a region overflow (the linker reports it), any allocated section other
     than .text and .bss (.data in particular), and patch symbols that
     shadow a firmware symbol;
  4. extract .text as the blob and read the patch's symbol table.

Needs arm-none-eabi-gcc, which the dev image has (docs/SETUP.md); ARM_GCC_BIN
overrides its directory. Run with `scripts/dev python -I tools/patch_build.py ...`.
"""
import csv
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
COMMON = ROOT / "patches" / "common"
SYMBOLS_CSV = ROOT / "docs" / "symbols" / "summit-2.2-2121.csv"
BUILD_DIR = ROOT / "work" / "build"

# Free flash: from the image end to the end of sector 6, which the update
# already erases (findings, "Integrity and free space").
FLASH_LIMIT = 0x08060000
# Patch RAM: CCM, which the firmware never references (findings, "Patch RAM").
PATCH_RAM = (0x10000000, 0x10000)
# Official image end for build 2121; patch.py passes the real one.
DEFAULT_ORIGIN = 0x080501C0

CFLAGS = [
    "-mcpu=cortex-m4", "-mthumb", "-mfloat-abi=hard", "-mfpu=fpv4-sp-d16",
    "-Os", "-std=c11", "-ffreestanding", "-nostdlib", "-fno-common",
    "-fno-tree-loop-distribute-patterns",  # no hidden memset/memcpy calls
    "-ffunction-sections", "-fno-unwind-tables", "-fno-asynchronous-unwind-tables",
    "-Wall", "-Wextra", "-Werror", "-g",
]
ALLOWED_SECTIONS = {".text", ".bss"}


class BuildError(Exception):
    pass


@dataclass
class Blob:
    """A linked patch: bytes for flash at *origin*, and its symbols."""
    origin: int
    data: bytes
    symbols: dict                 # name -> (value, type) from the ELF; FUNC values carry the Thumb bit
    bss: tuple                    # (start, end) of all patch RAM: zeroed .bss, then .noinit
    elf: Path
    firmware: dict = field(default_factory=dict)  # firmware symbol name -> address as linked
    fw_functions: set = field(default_factory=set)  # firmware function entry addresses (no Thumb bit)

    def address(self, name):
        """Address of a patch symbol; a function's has the Thumb bit set."""
        if name not in self.symbols:
            raise BuildError(f"patch symbol {name!r} not defined")
        return self.symbols[name][0]

    def is_function(self, name):
        return self.symbols.get(name, (0, ""))[1] == "FUNC"


def tool(name):
    """Path of an arm-none-eabi tool."""
    prefix = "arm-none-eabi-"
    bindir = os.environ.get("ARM_GCC_BIN")
    found = str(Path(bindir) / (prefix + name)) if bindir else shutil.which(prefix + name)
    if not found or not Path(found).exists():
        raise BuildError(f"{prefix}{name} not found (run it in the dev image: scripts/dev, docs/SETUP.md)")
    return found


def available():
    try:
        tool("gcc")
        return True
    except BuildError:
        return False


def _run(cmd, cwd=None):
    r = subprocess.run([str(c) for c in cmd], cwd=cwd, capture_output=True, text=True)
    if r.returncode:
        raise BuildError(f"{Path(str(cmd[0])).name} failed:\n{r.stdout}{r.stderr}".rstrip())
    return r.stdout


def firmware_symbols(csv_path=SYMBOLS_CSV):
    """name -> (link address, kind) from the symbols CSV; functions get the Thumb bit."""
    out = {}
    with open(csv_path, newline="") as f:
        for row in csv.DictReader(f):
            name, kind = row["name"].strip(), row["kind"].strip()
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", name):
                continue
            addr = int(row["address"], 16)
            if name in out:
                raise BuildError(f"{csv_path}: {name} defined twice")
            out[name] = (addr | 1 if kind == "function" else addr, kind)
    return out


def write_link_files(build_dir, origin, fw_syms):
    if origin % 4:
        raise BuildError(f"blob origin {origin:#x} is not 4-byte aligned")
    if not origin < FLASH_LIMIT:
        raise BuildError(f"blob origin {origin:#x} is not below {FLASH_LIMIT:#x}")
    ram, ram_size = PATCH_RAM
    (build_dir / "layout.ld").write_text(
        "/* Generated by tools/patch_build.py. */\n"
        "MEMORY\n{\n"
        f"    FREE_FLASH (rx) : ORIGIN = {origin:#010x}, LENGTH = {FLASH_LIMIT - origin:#x}\n"
        f"    PATCH_RAM (rw)  : ORIGIN = {ram:#010x}, LENGTH = {ram_size:#x}\n"
        "}\n")
    lines = [f"/* Generated by tools/patch_build.py from {SYMBOLS_CSV.relative_to(ROOT)}. */"]
    lines += [f"{name} = {addr:#010x};" for name, (addr, _) in sorted(fw_syms.items())]
    (build_dir / "fw_symbols.ld").write_text("\n".join(lines) + "\n")


def _symbols(elf):
    """name -> (value, type) for the defined global and local symbols of *elf*."""
    out = {}
    for line in _run([tool("readelf"), "-s", "-W", elf]).splitlines():
        parts = line.split()
        # Num: Value Size Type Bind Vis Ndx Name
        if len(parts) == 8 and re.fullmatch(r"\d+:", parts[0]) and parts[6] != "UND":
            out[parts[7]] = (int(parts[1], 16), parts[3])
    return out


def _sections(elf):
    """(name, address, size, flags) of every section header."""
    out = []
    for line in _run([tool("readelf"), "-S", "-W", elf]).splitlines():
        m = re.match(r"\s*\[\s*\d+\]\s+(\S+)\s+\S+\s+([0-9a-f]+)\s+[0-9a-f]+\s+([0-9a-f]+)\s+\S+\s*(\S*)", line)
        if m:
            out.append((m.group(1), int(m.group(2), 16), int(m.group(3), 16), m.group(4)))
    return out


def build(name, sources, origin=DEFAULT_ORIGIN, build_dir=None, csv_path=SYMBOLS_CSV):
    """Compile and link *sources*; return a :class:`Blob` placed at *origin*."""
    build_dir = Path(build_dir or BUILD_DIR / name)
    build_dir.mkdir(parents=True, exist_ok=True)
    fw_syms = firmware_symbols(csv_path)
    write_link_files(build_dir, origin, fw_syms)

    gcc = tool("gcc")
    objs = []
    for src in [Path(s) for s in sources] + sorted(COMMON.glob("*.c")):
        obj = build_dir / f"{src.parent.name}-{src.stem}.o"
        _run([gcc, *CFLAGS, f"-I{COMMON}", "-c", src, "-o", obj])
        objs.append(obj)

    # A patch function named like a firmware symbol would silently replace
    # the address C code means to call.
    for obj in objs:
        for line in _run([tool("nm"), "-g", "--defined-only", obj]).splitlines():
            sym = line.split()[-1]
            if sym in fw_syms:
                raise BuildError(f"{obj.name}: {sym} is a firmware symbol; give the patch function its own name")

    elf = build_dir / f"{name}.elf"
    _run([gcc, *CFLAGS, "-nostartfiles", f"-L{build_dir}", "-T", COMMON / "patch.ld",
          f"-Wl,-Map={build_dir / (name + '.map')}", "-Wl,--no-warn-rwx-segments",
          *objs, "-lgcc", "-o", elf])

    sections = {}
    for sec, addr, size, flags in _sections(elf):
        if "A" in flags and size:
            if sec not in ALLOWED_SECTIONS:
                raise BuildError(f"{elf.name}: section {sec} ({size} bytes) is not allowed; "
                                 "patch code may only have .text/.rodata (flash) and .bss (zeroed RAM)")
            sections[sec] = (addr, size)
    text_addr, text_size = sections.get(".text", (origin, 0))
    if text_addr != origin:
        raise BuildError(f".text at {text_addr:#x}, expected {origin:#x}")

    raw = build_dir / f"{name}.text"
    _run([tool("objcopy"), "-O", "binary", "-j", ".text", elf, raw])
    data = raw.read_bytes()
    if len(data) != text_size:
        raise BuildError(f"extracted {len(data)} bytes, .text is {text_size}")

    syms = _symbols(elf)
    bss = (syms["__patch_bss_start"][0], syms["__patch_ram_end"][0])  # zeroed .bss, then .noinit
    return Blob(origin, data, syms, bss, elf,
                {n: a for n, (a, _) in fw_syms.items()},
                {a & ~1 for a, kind in fw_syms.values() if kind == "function"})


def budget(blob):
    """Lines describing flash and RAM use."""
    flash_free = FLASH_LIMIT - blob.origin
    ram, ram_size = PATCH_RAM
    used = blob.bss[1] - blob.bss[0]
    return [
        f"blob    {blob.origin:#010x}-{blob.origin + len(blob.data):#010x}: {len(blob.data)} of "
        f"{flash_free} bytes free flash ({flash_free - len(blob.data)} left)",
        f"ram     {blob.bss[0]:#010x}-{blob.bss[1]:#010x}: {used} of {ram_size} bytes patch RAM "
        f"(CCM, {ram_size - used} left)",
    ]


def main(argv=None):
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import patch  # noqa: E402

    argv = sys.argv[1:] if argv is None else argv
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    try:
        definition = patch.load_definition(argv[0])
        blob = build(definition.NAME, patch.sources(definition))
    except (BuildError, patch.PatchError) as e:
        print(f"error: {e}", file=sys.stderr)
        return 1
    for line in budget(blob):
        print(line)
    print(f"elf     {blob.elf}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
