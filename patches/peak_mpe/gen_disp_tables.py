"""Generate disp_tables.h from the measured tables in docs/peak-units.md.

    python patches/peak_mpe/gen_disp_tables.py

Attack: the full ramp (ms). Decay and release: the time to -40 dB (ms). Both
at the settings the doc lists (every 4, plus a few), interpolated between
them geometrically (time is roughly exponential in the setting) and kept
monotonic. Below the measuring chain's resolution the entry is
the floor's value and the display shows "<Nms" (floors: attack 24, decay 28, release 12; DISP_*_FLOOR in disp.c). Filter: the self-oscillation frequency in Hz
for CC 29 0-127, interpolated geometrically to the 0-255 of the 9-bit knob;
values below CC 12 weren't measured and are extrapolated from the trend
(x1.62 per 8 steps, the doc's "near the middle"): see docs/peak-units.md.
"""
import math
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DOC = ROOT / "docs" / "peak-units.md"
OUT = Path(__file__).with_name("disp_tables.h")


def section(text, title):
    i = text.index(title)
    j = text.find("\n#", i + 10)
    return text[i:j if j > 0 else len(text)]


def rows(sec):
    out = []
    for line in sec.splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if cells and re.fullmatch(r"\d+", cells[0]) and line.startswith("|"):
            out.append(cells)
    return out


def num(x):
    try:
        return float(x)
    except ValueError:
        return None


def interp(points, n, geometric=True):
    """points: {x: y>0}; returns y for 0..n-1, geometric between neighbours."""
    xs = sorted(points)
    out = []
    for x in range(n):
        if x <= xs[0]:
            lo, hi = xs[0], xs[1]
        elif x >= xs[-1]:
            lo, hi = xs[-2], xs[-1]
        else:
            hi = next(v for v in xs if v >= x)
            lo = max(v for v in xs if v <= x)
            if lo == hi:
                out.append(points[lo])
                continue
        a, b = points[lo], points[hi]
        t = (x - lo) / (hi - lo)
        out.append(math.exp(math.log(a) + (math.log(b) - math.log(a)) * t) if geometric else a + (b - a) * t)
    return out


def monotone(v):
    m, out = 0.0, []
    for x in v:
        m = max(m, x)
        out.append(m)
    return out


def main():
    text = DOC.read_text(encoding="utf-8")
    attack = {int(r[0]): num(r[5]) * 1000 for r in rows(section(text, "#### Attack"))}
    decay = {int(r[0]): num(r[3]) * 1000 for r in rows(section(text, "#### Decay")) if num(r[3])}
    release = {int(r[0]): num(r[3]) * 1000 for r in rows(section(text, "#### Release")) if num(r[3])}
    filt = {int(r[0]): num(r[1]) for r in rows(section(text, "#### Filter table")) if int(r[0]) >= 12}

    def ms_table(points, floor_at):
        pts = {k: v for k, v in points.items() if k >= floor_at and v > 0}
        t = monotone(interp(pts, 128))
        # monotone() keeps early noise from pulling later values down; entries
        # below the resolution limit show as "<10ms"
        # below floor_at the entry is the floor's own time: shown as "<Nms"
        return [min(65535, round(t[max(i, floor_at)])) for i in range(128)]

    att = ms_table(attack, 24)
    dec = ms_table(decay, 28)
    rel = ms_table(release, 12)
    # Filter: measured CC 12..127 (the 4-step grid and 127); lower CCs follow
    # the near-middle slope. 256 entries: knob value k is CC k/2.
    pts = dict(filt)
    cc = interp(pts, 128)
    ratio = 1.62 ** (1 / 8)
    for i in range(12):
        cc[i] = cc[12] / ratio ** (12 - i)
    f = []
    for k in range(256):
        lo = k // 2
        hi = min(127, lo + 1)
        f.append(round(math.exp((math.log(cc[lo]) + math.log(cc[hi])) / 2)) if k & 1 else round(cc[lo]))

    def arr(name, v, ty="uint16_t"):
        lines = ["static const %s %s[%d] = {" % (ty, name, len(v))]
        for i in range(0, len(v), 16):
            lines.append("    " + ", ".join(str(x) for x in v[i:i + 16]) + ",")
        lines.append("};")
        return "\n".join(lines)

    OUT.write_text(
        "/* Generated by gen_disp_tables.py from docs/peak-units.md. Do not edit. */\n"
        "#ifndef DISP_TABLES_H\n#define DISP_TABLES_H\n#include <stdint.h>\n\n"
        "/* Attack: full ramp, ms (entries below the floor repeat the floor's time). */\n" + arr("disp_attack_ms", att) + "\n\n"
        "/* Decay: time to -40 dB, ms (entries below the floor repeat the floor's time). */\n" + arr("disp_decay_ms", dec) + "\n\n"
        "/* Release: time to -40 dB, ms (entries below the floor repeat the floor's time). */\n" + arr("disp_release_ms", rel) + "\n\n"
        "/* Filter cutoff, Hz, by the 9-bit knob value (CC 29 x 2 + fine bit). */\n" + arr("disp_cutoff_hz", f) + "\n\n"
        "#endif\n", encoding="utf-8", newline="\n")
    print("wrote", OUT, "attack", att[::16], "decay", dec[::16], "release", rel[::16], "cutoff", f[::32], f[-1])


if __name__ == "__main__":
    main()
